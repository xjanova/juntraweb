<?php

namespace App\Support;

use App\Models\Setting;

/**
 * ปิดขายบริการชั่วคราว — แยกจาก "เก็บเงิน/ฟรี" (Pricing) โดยเจตนา
 *
 * ปิดขาย = ลูกค้าใช้บริการนั้นไม่ได้เลย (ไม่หักเงิน ไม่คำนวณ) หน้าเว็บบอกเหตุผล ลิงก์เดิมไม่พัง
 * ต่างจากปิดสวิตช์เก็บเงินที่ยังให้ใช้ต่อแบบฟรี — ใช้ตอนที่ "ผลลัพธ์ยังไม่ถูกต้อง" ห้ามส่งถึงมือลูกค้า
 * แม้จะฟรีก็ตาม (CLAUDE.md: ยอมทำน้อยแต่ถูก ดีกว่าทำครบแต่มั่ว)
 *
 * เจ้าของสั่งปิด (2026-09-15) หลังเทียบกับ GenLotto (ตรวจกับ myhora/ปฏิทินหลวงแล้ว):
 *   - เลขศาสตร์: ตารางค่าอักษรไทยเป็นสูตรประมาณ (พยัญชนะ = 2 · สระ = 1) ผิด 63/73 ตัว
 *   - ฤกษ์ยาม: ขึ้น/แรมกี่ค่ำไม่ตรงปฏิทินหลวง 41% ของวัน + น้ำหนักวันขัดตำรา
 *     (แนะนำแต่งงานวันพุธ/พฤหัส · แนะนำวันที่เป็นฤกษ์โลกาวินาศของปี)
 */
final class ServiceGate
{
    /** บริการที่ปิดขายได้ → ชื่อที่ลูกค้าเห็น */
    public const SERVICES = [
        'numerology' => 'ดวงเลขศาสตร์',
        'auspicious' => 'หาฤกษ์ยาม',
    ];

    public static function isClosed(string $service): bool
    {
        return isset(self::SERVICES[$service]) && Setting::get("service_{$service}_closed") === '1';
    }

    public static function message(string $service): string
    {
        $name = self::SERVICES[$service] ?? 'นี้';

        return "ขออภัยค่ะ บริการ{$name}ปิดปรับปรุงชั่วคราว เพื่อให้ผลคำนวณตรงตามตำราและปฏิทินหลวงทุกวัน"
            .' — ยังไม่มีการหักเครดิต แม่หมอจะเปิดให้ใช้อีกครั้งเร็ว ๆ นี้ค่ะ';
    }
}
