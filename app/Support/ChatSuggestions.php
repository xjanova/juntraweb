    /**
     * แม่หมอกำลัง "ถามกลับ" อยู่หรือเปล่า
     *
     * ใช้ตัดสินว่าจะยุบแถบปุ่มคำถามลัดไหม — ถ้าแม่หมอเพิ่งถามขอข้อมูล
     * (วันเกิด ชื่อ ให้เลือกข้อ) แล้วผู้ใช้ดันกดปุ่มคำถามทั่วไป
     * บทสนทนาจะหลุดโฟลว์ทำนายทันที (บอทฝั่ง Thaiprompt มี state machine
     * เก็บคำตอบทีละขั้น — ข้อความที่ส่งไปจะถูกตีความเป็นคำตอบของคำถามนั้น)
     */
    public static function isAwaitingAnswer(?string $lastAssistantMessage): bool
    {
        $text = trim((string) $lastAssistantMessage);
        if ($text === '') {
            return false;
        }

        // ดูเฉพาะท้ายข้อความ — คำถามที่แม่หมอ "รอคำตอบ" มักปิดท้ายข้อความเสมอ
        $tail = mb_substr($text, -220);

        $asksForData = [
            'วันเกิด', 'วันเดือนปีเกิด', 'ปีเกิด', 'เวลาเกิด', 'เวลาตกฟาก',
            'ชื่อจริง', 'ชื่อ-นามสกุล', 'ชื่อนามสกุล', 'บอกชื่อ',
            'พิมพ์ชื่อ', 'พิมพ์วัน', 'พิมพ์เลข', 'พิมพ์ตัวเลข', 'พิมพ์ว่า',
            'เลือกข้อ', 'เลือกหมายเลข', 'เลือกแบบ', 'ตอบว่า',
            'กดเลือก', 'ยืนยัน', 'ใช่หรือไม่', 'ใช่ไหม',
        ];
        foreach ($asksForData as $needle) {
            if (mb_strpos($tail, $needle) !== false) {
                return true;
            }
        }

        return false;
    }

    /**
     * ชุดปุ่มสำหรับสถานะปัจจุบัน — จุดเดียวที่ตัดสินว่าจะโชว์ปุ่มชุดไหน
     *
     * @param  string  $state  'reading' | 'fresh' | 'flowing'
     */
    public static function forState(string $state, ?Reading $reading = null): array
    {
        return match ($state) {
            'reading' => self::forReading($reading),
            'fresh'   => self::starter(),
            default   => self::followUp(),
        };
    }

    /** @return array{label:string,prompt:string,icon:string} */
    private static function chip(string $label, string $prompt, string $icon): array
    {
        return ['label' => $label, 'prompt' => $prompt, 'icon' => $icon];
    }
