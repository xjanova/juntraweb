    /** @return array<string,string> key => label (สำหรับ dropdown) */
    public static function options(): array
    {
        return array_map(fn ($o) => $o['icon'].' '.$o['label'], self::LIST);
    }

    public static function has(?string $key): bool
    {
        return $key !== null && isset(self::LIST[$key]);
    }

    /** @return array{label:string,icon:string,keywords:array,ruek:array,weekday:array,waxing:bool,note:string} */
    public static function get(?string $key): array
    {
        return self::LIST[$key] ?? self::LIST[self::DEFAULT];
    }

    /**
     * เดาหมวดจากข้อความที่ลูกค้าพิมพ์ — คืน key ของหมวด
     *
     * เทียบ keyword ที่ยาวที่สุดก่อน เพื่อไม่ให้ "ย้ายร้าน" ถูก "ร้าน" ดูดไปหมวดค้าขาย
     */
    public static function detect(?string $text): string
    {
        $text = trim((string) $text);
        if ($text === '') {
            return self::DEFAULT;
        }

        $best = null;
        $bestLen = 0;
        foreach (self::LIST as $key => $def) {
            foreach ($def['keywords'] as $kw) {
                if (mb_strlen($kw) > $bestLen && mb_stripos($text, $kw) !== false) {
                    $best = $key;
                    $bestLen = mb_strlen($kw);
                }
            }
        }

        return $best ?? self::DEFAULT;
    }
