  <h2>1. การยอมรับข้อตกลง</h2>
  <p>ข้อตกลงนี้เป็นสัญญาระหว่างคุณ (“ผู้ใช้”) กับ <strong>{{ config('app.name', 'แม่หมอจันทรา') }}</strong> (จันทราพยากรณ์ · จันทรา.online) (“เรา”) เมื่อคุณสมัครสมาชิก เข้าสู่ระบบ หรือใช้บริการใด ๆ ถือว่าคุณได้อ่าน เข้าใจ และยอมรับข้อตกลงนี้ รวมถึง<a href="{{ route('legal.privacy') }}">นโยบายความเป็นส่วนตัว</a> แล้ว หากคุณไม่ยอมรับ กรุณางดใช้บริการ</p>

  <h2>2. ลักษณะของบริการ</h2>
  <p>เราให้บริการดูดวงและพยากรณ์ออนไลน์ที่ผสานศาสตร์โบราณกับปัญญาประดิษฐ์ ได้แก่ ไพ่ยิปซี ดวงรายวันและราศี เลขศาสตร์ ดูลายมือ การหาฤกษ์มงคล และ AI Chat พยากรณ์ บริการบางส่วนเปิดให้ใช้ฟรี และบางส่วนมีค่าบริการที่หักจากเครดิตในบัญชีของคุณ</p>

  <h2>3. ข้อจำกัดความรับผิดชอบที่สำคัญ</h2>
  <div class="legal-note">
    <p><strong>บริการนี้มีวัตถุประสงค์เพื่อความบันเทิงและเป็นแนวทางในการไตร่ตรองเท่านั้น</strong> คำพยากรณ์ไม่ใช่ และไม่อาจใช้แทน คำแนะนำจากผู้เชี่ยวชาญทางการแพทย์ กฎหมาย การเงิน การลงทุน หรือจิตวิทยา</p>
    <p>คำทำนายบางส่วนสร้างขึ้นโดยระบบ AI ซึ่งอาจมีความคลาดเคลื่อนหรือไม่ถูกต้อง การตัดสินใจใด ๆ จากคำพยากรณ์เป็นดุลพินิจและความรับผิดชอบของคุณแต่เพียงผู้เดียว หากคุณมีปัญหาสุขภาพ การเงิน หรือกฎหมาย โปรดปรึกษาผู้เชี่ยวชาญที่มีคุณสมบัติ</p>
  </div>

  <h2>4. คุณสมบัติของผู้ใช้</h2>
  <p>คุณต้องมีอายุ 18 ปีบริบูรณ์ขึ้นไป หรือใช้บริการภายใต้ความยินยอมและการดูแลของผู้ปกครอง และต้องให้ข้อมูลที่ถูกต้องและเป็นความจริงในการสมัครสมาชิก</p>

  <h2>5. บัญชีผู้ใช้และความปลอดภัย</h2>
  <ul>
    <li>คุณมีหน้าที่รักษารหัสผ่านและข้อมูลการเข้าสู่ระบบ (รวมถึงการเข้าสู่ระบบผ่าน Thaiprompt SSO) ไว้เป็นความลับ</li>
    <li>คุณรับผิดชอบต่อกิจกรรมทั้งหมดที่เกิดขึ้นภายใต้บัญชีของคุณ</li>
    <li>โปรดแจ้งเราทันทีหากพบการเข้าใช้งานบัญชีโดยไม่ได้รับอนุญาต</li>
  </ul>

  <h2>6. เครดิต การเติมเงิน และการชำระเงิน</h2>
  <ul>
    <li>บริการบางอย่างมีค่าบริการที่หักจากยอดเครดิตในบัญชีของคุณ โดยจะแสดงราคาก่อนการใช้งาน</li>
    <li>การเติมเงินทำผ่าน PromptPay พร้อมการอัปโหลดสลิปเพื่อยืนยัน เครดิตจะถูกเพิ่มเข้าบัญชีหลังการตรวจสอบโดยทีมงาน</li>
    <li>เครดิตใช้สำหรับบริการภายในเว็บไซต์เท่านั้น <strong>ไม่สามารถแลกเปลี่ยนเป็นเงินสด โอน หรือถอนออกได้</strong></li>
  </ul>

  <h3>นโยบายการคืนเงิน</h3>
  <ul>
    <li>เครดิตหรือบริการที่ถูกใช้ไปแล้ว (เช่น คำพยากรณ์ที่สร้างเสร็จแล้ว) <strong>ไม่สามารถขอคืนได้</strong> เนื่องจากเป็นบริการดิจิทัลที่ส่งมอบทันที</li>
    <li>กรณีระบบทำงานผิดพลาด หักเครดิตซ้ำซ้อน หรือชำระเงินสำเร็จแต่ไม่ได้รับเครดิต กรุณาติดต่อเราพร้อมหลักฐาน เราจะตรวจสอบและแก้ไขให้อย่างเป็นธรรม</li>
  </ul>

  <h2>7. ระบบแนะนำและเครือข่ายผู้แนะนำ</h2>
  <p>หากคุณเข้าร่วมระบบแนะนำ/เครือข่ายผู้แนะนำ (เชื่อมโยงกับ Thaiprompt-Affiliate) ค่าตอบแทนและเงื่อนไขเป็นไปตามข้อกำหนดของระบบนั้น คุณต้องไม่ให้ข้อมูลอันเป็นเท็จ ชักชวนด้วยข้อความเกินจริง หรือกระทำการใด ๆ ที่ผิดกฎหมายเพื่อรับค่าตอบแทน</p>

  <h2>8. การใช้งานที่ยอมรับได้</h2>
  <p>คุณตกลงว่าจะไม่</p>
  <ul>
    <li>ใช้บริการเพื่อวัตถุประสงค์ที่ผิดกฎหมาย หรือหลอกลวงผู้อื่น</li>
    <li>อัปโหลดเนื้อหาที่ผิดกฎหมาย ละเมิดสิทธิผู้อื่น หรือภาพถ่ายของบุคคลอื่นโดยไม่ได้รับความยินยอม</li>
    <li>พยายามเจาะระบบ ทำวิศวกรรมย้อนกลับ หรือรบกวนการทำงานและความปลอดภัยของระบบ</li>
    <li>ใช้บอท สคริปต์อัตโนมัติ หรือส่งคำขอจำนวนมากเพื่อสร้างภาระแก่ระบบ (เราใช้การจำกัดอัตราการใช้งานเพื่อป้องกันการใช้งานในทางที่ผิด)</li>
    <li>คัดลอก ทำซ้ำ หรือนำเนื้อหาของเราไปใช้ในเชิงพาณิชย์โดยไม่ได้รับอนุญาต</li>
  </ul>

  <h2>9. ทรัพย์สินทางปัญญา</h2>
  <p>เนื้อหา การออกแบบ โลโก้ ข้อความ ภาพไพ่ และซอฟต์แวร์บนเว็บไซต์เป็นทรัพย์สินทางปัญญาของเราหรือผู้ให้สิทธิ ห้ามนำไปใช้ ทำซ้ำ หรือดัดแปลงโดยไม่ได้รับอนุญาตเป็นลายลักษณ์อักษร</p>

  <h2>10. เนื้อหาที่ผู้ใช้ส่ง</h2>
  <p>เมื่อคุณส่งคำถาม ข้อความ หรือภาพถ่ายลายมือ คุณยังคงเป็นเจ้าของเนื้อหานั้น แต่อนุญาตให้เราประมวลผลและส่งต่อไปยังระบบ AI เท่าที่จำเป็นเพื่อสร้างคำพยากรณ์และให้บริการแก่คุณ ตามที่ระบุใน<a href="{{ route('legal.privacy') }}">นโยบายความเป็นส่วนตัว</a></p>

  <h2>11. การจำกัดความรับผิด</h2>
  <p>บริการให้ “ตามสภาพที่เป็นอยู่” (as is) เราไม่รับประกันความถูกต้อง ความแม่นยำ หรือความต่อเนื่องของบริการ ภายในขอบเขตสูงสุดที่กฎหมายอนุญาต เราจะไม่รับผิดต่อความเสียหายทางอ้อม ความเสียหายต่อเนื่อง หรือความสูญเสียใด ๆ ที่เกิดจากการใช้หรือการไม่สามารถใช้บริการ หรือจากการพึ่งพาคำพยากรณ์</p>

  <h2>12. การระงับและยกเลิกบัญชี</h2>
  <p>เราขอสงวนสิทธิในการระงับหรือยกเลิกบัญชีที่ละเมิดข้อตกลงนี้ ใช้งานในทางที่ผิด หรือก่อให้เกิดความเสี่ยงต่อระบบหรือผู้ใช้อื่น คุณสามารถขอลบบัญชีของคุณได้ตลอดเวลา</p>

  <h2>13. การเปลี่ยนแปลงข้อตกลงและบริการ</h2>
  <p>เราอาจปรับปรุงข้อตกลงนี้ หรือเปลี่ยนแปลง ระงับ หรือยุติบริการบางส่วนได้ การเปลี่ยนแปลงจะมีผลเมื่อเผยแพร่บนหน้านี้ การใช้บริการต่อหลังการเปลี่ยนแปลงถือว่าคุณยอมรับข้อตกลงฉบับใหม่</p>

  <h2>14. กฎหมายที่ใช้บังคับ</h2>
